/**
 * 社交名片：平台注册表 + 配置读写
 *
 * 新增一个平台只需在 SOCIAL_PLATFORMS 里加一条：
 *   - 品牌图标填 path（24x24 viewBox 的单条 SVG path，fill 渲染）
 *   - 通用图标填 lucide（lucide-react 的图标名，stroke 渲染）
 * 品牌 path 可从 simple-icons 取：
 *   https://cdn.jsdelivr.net/npm/simple-icons@15/icons/<slug>.svg
 */

export interface SocialPlatform {
  key: string;
  label: string;
  /** 品牌图标的 SVG path（与 lucide 二选一） */
  path?: string;
  /** lucide 图标名（与 path 二选一） */
  lucide?: string;
  /** 地址输入框的占位提示 */
  placeholder?: string;
}

export interface SocialLink {
  id: string;
  /** 对应 SOCIAL_PLATFORMS 的 key */
  platform: string;
  url: string;
  /** 自定义悬浮提示，留空则用平台名 */
  label?: string;
}

/** 最多允许配置的链接数，避免页头挤爆 */
export const MAX_SOCIAL_LINKS = 12;

const SAFE_PROTOCOLS = ["http:", "https:", "mailto:", "tg:"];

/** 校验地址协议，挡掉 javascript: 之类的注入 */
export function isSafeUrl(url: string): boolean {
  try {
    return SAFE_PROTOCOLS.includes(new URL(url).protocol);
  } catch {
    return false;
  }
}

/** 从 config.social_links 的 JSON 字符串解析，脏数据一律丢弃而不抛错 */
export function parseSocialLinks(json: string): SocialLink[] {
  if (!json) return [];
  let raw: unknown;
  try {
    raw = JSON.parse(json);
  } catch {
    return [];
  }
  if (!Array.isArray(raw)) return [];

  return raw
    .filter((it): it is Record<string, unknown> => !!it && typeof it === "object")
    .map((it) => ({
      id: typeof it.id === "string" ? it.id : "",
      platform: typeof it.platform === "string" ? it.platform : "",
      url: typeof it.url === "string" ? it.url.trim() : "",
      label: typeof it.label === "string" ? it.label : undefined,
    }))
    .filter((it) => it.id && it.url && isSafeUrl(it.url) && !!getPlatform(it.platform))
    .slice(0, MAX_SOCIAL_LINKS);
}

export function serializeSocialLinks(links: SocialLink[]): string {
  return JSON.stringify(
    links.map((l) => ({
      id: l.id,
      platform: l.platform,
      url: l.url,
      ...(l.label ? { label: l.label } : {}),
    }))
  );
}

export function getPlatform(key: string): SocialPlatform | undefined {
  return SOCIAL_PLATFORMS.find((p) => p.key === key);
}

/** 悬浮提示文案 */
export function getSocialLabel(link: SocialLink): string {
  return link.label?.trim() || getPlatform(link.platform)?.label || link.platform;
}

